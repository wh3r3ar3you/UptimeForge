// Package store persists configuration made in the UI, users, incident
// history and time series in PostgreSQL.
package store

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
	"strings"
	"sync"
	"time"

	"github.com/jackc/pgx/v5/pgconn"
	_ "github.com/jackc/pgx/v5/stdlib"
)

type Store struct {
	db *sql.DB

	mu       sync.Mutex
	series   map[[2]string]int64 // (check, probe) -> series id
	dirty    int64               // oldest sample ts written since the last rollup
	sysDirty int64

	reads chan struct{} // slots for heavy UI reads, see read
}

// Heavy reads behind the UI (charts, history, reports) may hold at most
// maxReads of the pool's maxConns connections, and run at most readTimeout:
// a burst of them must leave the recorder room to write.
const (
	maxConns = 16
	maxReads = 10
)

var readTimeout = 30 * time.Second // a var for tests

// read takes a read slot and bounds the query's time. Call done when the
// rows are closed.
func (s *Store) read(ctx context.Context) (rctx context.Context, done func(), err error) {
	select {
	case s.reads <- struct{}{}:
	case <-ctx.Done():
		return ctx, func() {}, ctx.Err()
	}
	rctx, cancel := context.WithTimeout(ctx, readTimeout)
	return rctx, func() { cancel(); <-s.reads }, nil
}

var ErrNotFound = errors.New("not found")

// connectWait covers the database container starting next to the hub.
const connectWait = 30 * time.Second

// Open connects to postgres://… and brings the schema up to date.
func Open(url string) (*Store, error) {
	if url == "" {
		return nil, errors.New("database URL is empty: set UF_DATABASE_URL to postgres://user:password@host:5432/db")
	}
	db, err := sql.Open("pgx", url)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(maxConns)
	db.SetMaxIdleConns(4)
	db.SetConnMaxLifetime(time.Hour)
	if err := ping(db); err != nil {
		db.Close()
		return nil, fmt.Errorf("connect to PostgreSQL: %w", err)
	}
	var version int
	if err := db.QueryRow(`SELECT current_setting('server_version_num')::int`).Scan(&version); err != nil {
		db.Close()
		return nil, fmt.Errorf("read PostgreSQL version: %w", err)
	}
	if err := checkServerVersion(version); err != nil {
		db.Close()
		return nil, err
	}
	s := &Store{db: db, series: map[[2]string]int64{}, reads: make(chan struct{}, maxReads)}
	if err := s.migrate(); err != nil {
		db.Close()
		return nil, err
	}
	return s, nil
}

// Permanent says the database refused the data itself (a value out of range,
// a constraint, bad SQL): writing the same rows again fails the same way.
// Lost connections, timeouts, shutdowns and deadlocks are not permanent.
func Permanent(err error) bool {
	var pe *pgconn.PgError
	if !errors.As(err, &pe) || len(pe.Code) < 2 {
		return false
	}
	switch pe.Code[:2] {
	case "08", "40", "53", "55", "57", "58", "XX": // connection, rollback, resources, lock, shutdown, system
		return false
	}
	return true
}

// checkServerVersion refuses servers older than PostgreSQL 14: rollups and
// charts bucket time with date_bin, which 14 introduced. version is
// server_version_num, e.g. 140005.
func checkServerVersion(version int) error {
	if version < 140000 {
		return fmt.Errorf("PostgreSQL %d.%d is too old: UptimeForge needs PostgreSQL 14 or newer (date_bin)", version/10000, version%10000)
	}
	return nil
}

func ping(db *sql.DB) error {
	deadline := time.Now().Add(connectWait)
	for {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		err := db.PingContext(ctx)
		cancel()
		if err == nil || time.Now().After(deadline) {
			return err
		}
		time.Sleep(time.Second)
	}
}

func (s *Store) Close() error { return s.db.Close() }

// DB is for tools that move data in bulk.
func (s *Store) DB() *sql.DB { return s.db }

