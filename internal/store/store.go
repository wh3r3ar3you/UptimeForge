// Hubs racing to migrate the same database take turns on this lock.
const migrateLock = 0x75667472 // "uftr"

func (s *Store) migrate() error {
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := tx.Exec(`SELECT pg_advisory_xact_lock($1)`, migrateLock); err != nil {
		return err
	}
	if _, err := tx.Exec(`CREATE TABLE IF NOT EXISTS schema_version (v INTEGER NOT NULL)`); err != nil {
		return err
	}
	var v int
	if err := tx.QueryRow(`SELECT COALESCE(MAX(v), 0) FROM schema_version`).Scan(&v); err != nil {
		return err
	}
	if v > len(migrations) {
		return fmt.Errorf("database schema %d is newer than this hub understands (%d): upgrade the hub", v, len(migrations))
	}
	for i := v; i < len(migrations); i++ {
		if _, err := tx.Exec(migrations[i]); err != nil {
			return fmt.Errorf("migration %d: %w", i+1, err)
		}
		if _, err := tx.Exec(`INSERT INTO schema_version (v) VALUES ($1)`, i+1); err != nil {
			return err
		}
	}
	return tx.Commit()
}

// cleanJSON drops \u0000 escapes, which jsonb refuses. They reach us in text
// taken from remote servers, and losing an incident to one is not an option.
func cleanJSON(b []byte) string {
	const nul = `\u0000`
	s := string(b)
	if !strings.Contains(s, nul) {
		return s
	}
	var out strings.Builder
	for i := 0; i < len(s); i++ {
		if s[i] != '\\' {
			out.WriteByte(s[i])
			continue
		}
		if strings.HasPrefix(s[i:], nul) {
			i += len(nul) - 1
			continue
		}
		out.WriteByte(s[i])
		if i++; i < len(s) { // the escaped character, so `\\u0000` stays text
			out.WriteByte(s[i])
		}
	}
	return out.String()
}

// CleanJSON is cleanJSON for tools that write JSON directly.
func CleanJSON(b []byte) string { return cleanJSON(b) }

// cleanText drops NUL bytes, which text columns refuse.
func cleanText(s string) string { return strings.ReplaceAll(s, "\x00", "") }

// GetSetting decodes the JSON stored under key into v. found is false when
// the key was never written.
func (s *Store) GetSetting(ctx context.Context, key string, v any) (found bool, err error) {
	var raw string
	err = s.db.QueryRowContext(ctx, `SELECT value FROM settings WHERE key = $1`, key).Scan(&raw)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return true, json.Unmarshal([]byte(raw), v)
}

func (s *Store) PutSetting(ctx context.Context, key string, v any) error {
	b, err := json.Marshal(v)
	if err != nil {
		return err
	}
	_, err = s.db.ExecContext(ctx, `INSERT INTO settings (key, value) VALUES ($1, $2)
		ON CONFLICT (key) DO UPDATE SET value = excluded.value`, key, cleanJSON(b))
	return err
}

// Object is a configuration item created in the UI (probe, check, status page).
type Object struct {
	Kind    string
	ID      string
	Pos     int
	Data    json.RawMessage
	Created time.Time
	Updated time.Time
}

func (s *Store) Objects(ctx context.Context, kind string) ([]Object, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT id, pos, data, created, updated FROM objects WHERE kind = $1 ORDER BY pos, created`, kind)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Object
	for rows.Next() {
		o := Object{Kind: kind}
		var data string
		if err := rows.Scan(&o.ID, &o.Pos, &data, &o.Created, &o.Updated); err != nil {
			return nil, err
		}
		o.Data = json.RawMessage(data)
		out = append(out, o)
	}
	return out, rows.Err()
}

func (s *Store) GetObject(ctx context.Context, kind, id string, v any) error {
	var data string
	err := s.db.QueryRowContext(ctx, `SELECT data FROM objects WHERE kind = $1 AND id = $2`, kind, id).Scan(&data)
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	if err != nil {
		return err
	}
	return json.Unmarshal([]byte(data), v)
}

// PutObject inserts or replaces; new objects go to the end of the list.
func (s *Store) PutObject(ctx context.Context, kind, id string, v any) error {
	b, err := json.Marshal(v)
	if err != nil {
		return err
	}
	now := time.Now()
	_, err = s.db.ExecContext(ctx, `INSERT INTO objects (kind, id, pos, data, created, updated)
		VALUES ($1, $2, (SELECT COALESCE(MAX(pos), 0) + 1 FROM objects WHERE kind = $3), $4, $5, $6)
		ON CONFLICT (kind, id) DO UPDATE SET data = excluded.data, updated = excluded.updated`,
		kind, id, kind, cleanJSON(b), now, now)
	return err
}

func (s *Store) DeleteObject(ctx context.Context, kind, id string) error {
	res, err := s.db.ExecContext(ctx, `DELETE FROM objects WHERE kind = $1 AND id = $2`, kind, id)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}
